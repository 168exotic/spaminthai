#!/usr/bin/env node
/**
 * Build functions/news/news-index.js from news/*.html (title, date, provinces).
 * Run after adding/editing news:  node scripts/build-news-index.mjs
 * Province pages and number pages use the index to link to related news
 * (internal links เบอร์ ↔ จังหวัด ↔ ข่าว in the 90-day plan, Phase 1).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REGIONS } from '../functions/province/provinces.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NEWS_DIR = path.join(ROOT, 'news');
const OUT = path.join(ROOT, 'functions/news/news-index.js');

// Names that are also everyday Thai words: only match with "จ." / "จังหวัด" in front.
const AMBIGUOUS = new Set(['เลย', 'แพร่', 'ตาก', 'น่าน', 'ตรัง', 'พัง']);
const EXTRA = {
  bangkok: ['กรุงเทพ', 'กทม.'],
  'nakhon-ratchasima': ['โคราช'],
  ayutthaya: ['อยุธยา'],
  chonburi: ['พัทยา'],
  songkhla: ['หาดใหญ่'],
  tak: ['แม่สอด'],
};

const provinceTerms = [];
for (const [, list] of REGIONS) {
  for (const [slug, , th] of list) {
    const terms = AMBIGUOUS.has(th) ? [`จ.${th}`, `จังหวัด${th}`] : [th, ...(EXTRA[slug] || [])];
    provinceTerms.push([slug, terms]);
  }
}

const strip = (s) => String(s || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

export function parseNews(file, html) {
  const slug = file.replace(/\.html$/, '');
  const title = strip((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1] || (html.match(/<title>([^<]*)<\/title>/) || [])[1])
    .replace(/\s*\|\s*SpamInThai\s*$/, '');
  const date = ((html.match(/"datePublished"\s*:\s*"([^"]+)"/) || [])[1] || '').slice(0, 10);
  const lead = strip((html.match(/<p class="lead">([\s\S]*?)<\/p>/) || [])[1]);
  const hay = title + ' ' + lead;
  const provinces = provinceTerms.filter(([, terms]) => terms.some((t) => hay.includes(t))).map(([s]) => s);
  const noindex = /<meta[^>]+name="robots"[^>]+noindex/i.test(html);
  return { slug, title, date, provinces, noindex };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const items = fs
    .readdirSync(NEWS_DIR)
    .filter((f) => f.endsWith('.html') && f !== 'index.html')
    .map((f) => parseNews(f, fs.readFileSync(path.join(NEWS_DIR, f), 'utf8')))
    .filter((n) => n.title && n.date && !n.noindex)
    .map(({ noindex, ...n }) => n)
    .sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
  const out = `// AUTO-GENERATED by scripts/build-news-index.mjs — do not edit by hand.
// Re-run after adding news:  node scripts/build-news-index.mjs
export const NEWS = ${JSON.stringify(items, null, 2)};
`;
  fs.writeFileSync(OUT, out);
  const withProv = items.filter((n) => n.provinces.length).length;
  console.log(`news-index: ${items.length} articles (${withProv} tagged with a province) -> ${path.relative(ROOT, OUT)}`);
}
