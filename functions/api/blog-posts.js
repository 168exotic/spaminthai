export function handleBlogLatest(request) {
  const url = new URL(request.url);
  const n = Math.min(Math.max(parseInt(url.searchParams.get('n') || '3', 10) || 3, 1), 12);
  const items = BLOG_POSTS.slice(0, n).map((p) => ({
    slug: p.slug,
    title: p.title,
    desc: p.desc,
    date: p.date,
    url: `/blog/${p.slug}`,
    image: `/assets/blog/${p.slug}.webp`,
  }));
  return new Response(JSON.stringify({ items }), {
    headers: {
      'content-type': 'application/json; charset=utf-8',
      'cache-control': 'public, max-age=300',
    },
  });
}
